"""Controlled phase-shift benchmark for NeuroMem's budget controller.

This is a deterministic trace-driven experiment, not an end-to-end application
benchmark.  It changes per-result retrieval cost between phases and compares
online control with fixed policies and a phase-aware offline oracle.  Reported
latencies are generated by the declared cost trace; controller overhead is
measured separately with the process monotonic clock.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import math
import os
import platform
import random
import statistics
import subprocess
import sys
from collections import deque
from dataclasses import asdict, dataclass
from pathlib import Path
from time import perf_counter_ns
from typing import Any

from sage.neuromem import BudgetController, EvictionCandidate, ResourceBudget

from .system_runtime_bench import latency_summary


@dataclass(frozen=True, slots=True)
class WorkloadPhase:
    name: str
    operations: int
    unit_latency_ms: float
    required_top_k: int
    write_every: int


DEFAULT_PHASES = (
    WorkloadPhase("warm", 80, 2.0, 4, 2),
    WorkloadPhase("cost_spike", 80, 8.0, 6, 2),
    WorkloadPhase("recovery", 80, 3.0, 8, 2),
)


def _run_command(command: list[str], *, cwd: Path | None = None) -> str:
    completed = subprocess.run(
        command,
        cwd=cwd,
        check=True,
        capture_output=True,
        text=True,
    )
    return completed.stdout.strip()


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _repository_provenance() -> dict[str, Any]:
    script_path = Path(__file__).resolve()
    benchmark_repo = script_path.parents[2]
    neuromem_root = (
        benchmark_repo.parent.parent
        if benchmark_repo.parent.name == "third_party"
        else Path(os.environ.get("NEUROMEM_ROOT", benchmark_repo.parent / "neuromem"))
    )
    return {
        "python": sys.version,
        "platform": platform.platform(),
        "command": [sys.executable, *sys.argv],
        "benchmark_script": str(script_path.relative_to(neuromem_root)),
        "benchmark_script_sha256": _sha256(script_path),
        "benchmark_revision": _run_command(
            ["git", "rev-parse", "HEAD"],
            cwd=benchmark_repo,
        ),
        "neuromem_revision": _run_command(
            ["git", "rev-parse", "HEAD"],
            cwd=neuromem_root,
        ),
        "submodule_revisions": _run_command(
            ["git", "submodule", "status", "--recursive"],
            cwd=neuromem_root,
        ).splitlines(),
    }


def _write_artifact_bundle(destination: Path, report: dict[str, Any]) -> None:
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(json.dumps(report, indent=2, sort_keys=True), encoding="utf-8")

    environment_path = destination.with_suffix(".environment.txt")
    environment_path.write_text(
        _run_command([sys.executable, "-m", "pip", "freeze"]) + "\n",
        encoding="utf-8",
    )
    manifest = {
        "report": destination.name,
        "report_sha256": _sha256(destination),
        "environment_lock": environment_path.name,
        "environment_lock_sha256": _sha256(environment_path),
        "provenance": report["provenance"],
    }
    manifest_path = destination.with_suffix(".manifest.json")
    manifest_path.write_text(json.dumps(manifest, indent=2, sort_keys=True), encoding="utf-8")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--seeds", default="11,23,47")
    parser.add_argument("--operations-per-phase", type=int, default=80)
    parser.add_argument("--latency-slo-ms", type=float, default=24.0)
    parser.add_argument("--state-budget-entries", type=int, default=64)
    parser.add_argument("--state-budget-bytes", type=int, default=8192)
    parser.add_argument("--requested-top-k", type=int, default=8)
    parser.add_argument("--observation-window", type=int, default=16)
    parser.add_argument("--overhead-warmup", type=int, default=2000)
    parser.add_argument("--overhead-batches", type=int, default=200)
    parser.add_argument("--overhead-batch-size", type=int, default=128)
    parser.add_argument("--output", default="")
    return parser.parse_args()


def _phase_trace(
    phase: WorkloadPhase,
    *,
    seed: int,
    requested_top_k: int,
) -> list[float]:
    rng = random.Random(f"{seed}:{phase.name}")
    return [rng.uniform(0.95, 1.05) for _ in range(phase.operations)]


def _offline_oracle_top_k(
    phase: WorkloadPhase,
    jitters: list[float],
    *,
    requested_top_k: int,
    latency_slo_ms: float,
) -> int:
    for top_k in range(requested_top_k, 0, -1):
        latencies = [2.0 + top_k * phase.unit_latency_ms * jitter for jitter in jitters]
        if latency_summary(latencies)["p95_ms"] <= latency_slo_ms:
            return top_k
    return 1


def _select_top_k(
    policy: str,
    *,
    controller: BudgetController | None,
    requested_top_k: int,
    oracle_top_k: int,
) -> int:
    if policy == "static_safe":
        return min(2, requested_top_k)
    if policy == "static_intermediate":
        return min(3, requested_top_k)
    if policy in {"static_aggressive", "no_controller"}:
        return requested_top_k
    if policy == "offline_oracle":
        return oracle_top_k
    if controller is None:
        raise RuntimeError("online controller policy requires a controller")
    return controller.decide_retrieval(requested_top_k).applied_top_k


def _apply_write(
    policy: str,
    *,
    controller: BudgetController | None,
    retained: deque[EvictionCandidate],
    next_entry_id: str,
    incoming_size_bytes: int,
    state_budget_entries: int,
    state_budget_bytes: int,
) -> None:
    candidate = EvictionCandidate(
        next_entry_id,
        float(next_entry_id.split("-")[-1]),
        incoming_size_bytes,
    )
    if policy == "no_controller":
        retained.append(candidate)
        return
    if policy != "online_controller":
        retained.append(candidate)
        while (
            len(retained) > state_budget_entries
            or sum(item.size_bytes for item in retained) > state_budget_bytes
        ):
            retained.popleft()
        return
    if controller is None:
        raise RuntimeError("online controller policy requires a controller")

    decision = controller.decide_admission(
        current_entries=len(retained),
        current_size_bytes=sum(item.size_bytes for item in retained),
        incoming_size_bytes=incoming_size_bytes,
        candidates=list(retained),
    )
    if decision.action == "reject":
        return
    victim_ids = set(decision.victim_ids)
    if victim_ids:
        retained_copy = [item for item in retained if item.entry_id not in victim_ids]
        retained.clear()
        retained.extend(retained_copy)
    retained.append(candidate)


def _adaptation_steps(
    applied_by_phase: dict[str, list[int]],
    oracle_by_phase: dict[str, int],
) -> dict[str, int | None]:
    adaptation = {}
    previous = None
    for phase_name, applied_values in applied_by_phase.items():
        target = oracle_by_phase[phase_name]
        prior_value = target if previous is None else previous
        decreasing = target < prior_value
        matched_at = None
        for index, value in enumerate(applied_values):
            reached = value <= target if decreasing else value >= target
            if reached:
                matched_at = index
                break
        adaptation[phase_name] = matched_at
        previous = target
    return adaptation


def run_trial(
    *,
    policy: str,
    seed: int,
    phases: tuple[WorkloadPhase, ...],
    requested_top_k: int,
    latency_slo_ms: float,
    state_budget_entries: int,
    state_budget_bytes: int,
    observation_window: int,
) -> dict[str, Any]:
    controller = None
    if policy == "online_controller":
        controller = BudgetController(
            ResourceBudget(
                max_entries=state_budget_entries,
                max_size_bytes=state_budget_bytes,
                retrieval_slo_ms=latency_slo_ms,
                observation_window=observation_window,
            ),
            overflow_policy="evict_oldest",
        )

    latencies = []
    qualities = []
    latency_violations = 0
    state_violations = 0
    retained: deque[EvictionCandidate] = deque()
    applied_by_phase: dict[str, list[int]] = {}
    oracle_by_phase: dict[str, int] = {}
    controller_overheads_us = []
    entry_sequence = 0

    for phase in phases:
        jitters = _phase_trace(phase, seed=seed, requested_top_k=requested_top_k)
        oracle_top_k = _offline_oracle_top_k(
            phase,
            jitters,
            requested_top_k=requested_top_k,
            latency_slo_ms=latency_slo_ms,
        )
        oracle_by_phase[phase.name] = oracle_top_k
        phase_applied = []

        for operation_index, jitter in enumerate(jitters):
            control_started = perf_counter_ns()
            applied_top_k = _select_top_k(
                policy,
                controller=controller,
                requested_top_k=requested_top_k,
                oracle_top_k=oracle_top_k,
            )
            control_elapsed_ns = perf_counter_ns() - control_started

            duration_ms = 2.0 + applied_top_k * phase.unit_latency_ms * jitter
            if controller is not None:
                observe_started = perf_counter_ns()
                controller.observe_retrieval(
                    duration_ms=duration_ms,
                    applied_top_k=applied_top_k,
                )
                control_elapsed_ns += perf_counter_ns() - observe_started
            controller_overheads_us.append(control_elapsed_ns / 1000.0)

            latencies.append(duration_ms)
            qualities.append(min(applied_top_k, phase.required_top_k) / phase.required_top_k)
            phase_applied.append(applied_top_k)
            latency_violations += int(duration_ms > latency_slo_ms)

            if phase.write_every > 0 and (operation_index + 1) % phase.write_every == 0:
                entry_sequence += 1
                size_pattern = (64, 192, 512, 96, 320)
                incoming_size_bytes = size_pattern[(entry_sequence + seed) % len(size_pattern)]
                _apply_write(
                    policy,
                    controller=controller,
                    retained=retained,
                    next_entry_id=f"entry-{entry_sequence}",
                    incoming_size_bytes=incoming_size_bytes,
                    state_budget_entries=state_budget_entries,
                    state_budget_bytes=state_budget_bytes,
                )
            retained_size_bytes = sum(item.size_bytes for item in retained)
            state_violations += int(
                len(retained) > state_budget_entries
                or retained_size_bytes > state_budget_bytes
            )

        applied_by_phase[phase.name] = phase_applied

    total_operations = sum(phase.operations for phase in phases)
    overhead_summary = {
        key.replace("_ms", "_us"): value
        for key, value in latency_summary(controller_overheads_us).items()
    }
    return {
        "policy": policy,
        "seed": seed,
        "operations": total_operations,
        "quality_proxy": sum(qualities) / len(qualities),
        "latency_ms": latency_summary(latencies),
        "latency_violation_rate": latency_violations / total_operations,
        "state_violation_rate": state_violations / total_operations,
        "retained_entries": len(retained),
        "retained_size_bytes": sum(item.size_bytes for item in retained),
        "controller_overhead_us": overhead_summary,
        "adaptation_steps": _adaptation_steps(applied_by_phase, oracle_by_phase),
        "oracle_top_k_by_phase": oracle_by_phase,
        "mean_top_k_by_phase": {
            name: sum(values) / len(values) for name, values in applied_by_phase.items()
        },
        "controller_snapshot": controller.snapshot() if controller else None,
    }


def _mean(values: list[float]) -> float:
    return sum(values) / len(values)


def _ci95(values: list[float]) -> float:
    if len(values) < 2:
        return 0.0
    critical_values = {
        2: 12.706,
        3: 4.303,
        4: 3.182,
        5: 2.776,
        6: 2.571,
        7: 2.447,
        8: 2.365,
        9: 2.306,
        10: 2.262,
    }
    critical = critical_values.get(len(values), 1.96)
    return critical * statistics.stdev(values) / math.sqrt(len(values))


def _metric(values: list[float]) -> dict[str, float]:
    return {"mean": _mean(values), "ci95": _ci95(values)}


def _measure_controller_overhead(
    *,
    latency_slo_ms: float,
    observation_window: int,
    warmup: int,
    batches: int,
    batch_size: int,
) -> dict[str, Any]:
    """Measure the decision/update path separately from the modeled trace."""
    if warmup < 0 or batches < 1 or batch_size < 1:
        raise ValueError("overhead measurement sizes must be positive")

    controller = BudgetController(
        ResourceBudget(
            retrieval_slo_ms=latency_slo_ms,
            observation_window=observation_window,
        )
    )
    for _ in range(observation_window):
        controller.observe_retrieval(duration_ms=20.0, applied_top_k=4)

    original_affinity: set[int] | None = None
    measurement_cpu: int | None = None
    if hasattr(os, "sched_getaffinity") and hasattr(os, "sched_setaffinity"):
        original_affinity = set(os.sched_getaffinity(0))
        if original_affinity:
            measurement_cpu = min(original_affinity)
            os.sched_setaffinity(0, {measurement_cpu})

    def invoke_once() -> None:
        decision = controller.decide_retrieval(8)
        controller.observe_retrieval(
            duration_ms=5.0 * decision.applied_top_k,
            applied_top_k=decision.applied_top_k,
        )

    try:
        for _ in range(warmup):
            invoke_once()
        per_operation_us = []
        for _ in range(batches):
            started = perf_counter_ns()
            for _ in range(batch_size):
                invoke_once()
            elapsed = perf_counter_ns() - started
            per_operation_us.append(elapsed / batch_size / 1000.0)
    finally:
        if original_affinity is not None:
            os.sched_setaffinity(0, original_affinity)

    return {
        "clock": "perf_counter_ns",
        "measurement_cpu": measurement_cpu,
        "warmup_operations": warmup,
        "batches": batches,
        "operations_per_batch": batch_size,
        "summary_us_per_decision_update": {
            key.replace("_ms", "_us"): value
            for key, value in latency_summary(per_operation_us).items()
        },
        "batch_means_us_per_decision_update": per_operation_us,
    }


def run_budget_control_benchmark(
    *,
    seeds: list[int],
    operations_per_phase: int = 80,
    latency_slo_ms: float = 24.0,
    state_budget_entries: int = 64,
    state_budget_bytes: int = 8192,
    requested_top_k: int = 8,
    observation_window: int = 16,
    overhead_warmup: int = 2000,
    overhead_batches: int = 200,
    overhead_batch_size: int = 128,
    output_path: str | Path | None = None,
) -> dict[str, Any]:
    phases = tuple(
        WorkloadPhase(
            phase.name,
            operations_per_phase,
            phase.unit_latency_ms,
            phase.required_top_k,
            phase.write_every,
        )
        for phase in DEFAULT_PHASES
    )
    policies = (
        "no_controller",
        "static_safe",
        "static_intermediate",
        "static_aggressive",
        "online_controller",
        "offline_oracle",
    )
    trials = [
        run_trial(
            policy=policy,
            seed=seed,
            phases=phases,
            requested_top_k=requested_top_k,
            latency_slo_ms=latency_slo_ms,
            state_budget_entries=state_budget_entries,
            state_budget_bytes=state_budget_bytes,
            observation_window=observation_window,
        )
        for policy in policies
        for seed in seeds
    ]
    aggregates = []
    for policy in policies:
        selected = [trial for trial in trials if trial["policy"] == policy]
        quality = [trial["quality_proxy"] for trial in selected]
        latency_violations = [trial["latency_violation_rate"] for trial in selected]
        state_violations = [trial["state_violation_rate"] for trial in selected]
        p95_latencies = [trial["latency_ms"]["p95_ms"] for trial in selected]
        overheads = [trial["controller_overhead_us"]["p95_us"] for trial in selected]
        aggregates.append(
            {
                "policy": policy,
                "trials": len(selected),
                "quality_proxy": _metric(quality),
                "latency_violation_rate": _metric(latency_violations),
                "state_violation_rate": _metric(state_violations),
                "p95_latency_ms": _metric(p95_latencies),
                "controller_p95_overhead_us": _metric(overheads),
            }
        )

    report = {
        "benchmark": "controlled_phase_shift",
        "latency_source": "declared deterministic cost trace",
        "controller_overhead_source": (
            "single-CPU batched microbenchmark using a monotonic wall clock"
        ),
        "config": {
            "seeds": seeds,
            "latency_slo_ms": latency_slo_ms,
            "state_budget_entries": state_budget_entries,
            "state_budget_bytes": state_budget_bytes,
            "payload_size_pattern_bytes": [64, 192, 512, 96, 320],
            "requested_top_k": requested_top_k,
            "observation_window": observation_window,
            "phases": [asdict(phase) for phase in phases],
        },
        "aggregates": aggregates,
        "trials": trials,
        "controller_overhead_microbenchmark": _measure_controller_overhead(
            latency_slo_ms=latency_slo_ms,
            observation_window=observation_window,
            warmup=overhead_warmup,
            batches=overhead_batches,
            batch_size=overhead_batch_size,
        ),
        "provenance": _repository_provenance(),
    }
    if output_path:
        _write_artifact_bundle(Path(output_path), report)
    return report


def main() -> None:
    args = parse_args()
    seeds = [int(item) for item in args.seeds.split(",") if item.strip()]
    report = run_budget_control_benchmark(
        seeds=seeds,
        operations_per_phase=args.operations_per_phase,
        latency_slo_ms=args.latency_slo_ms,
        state_budget_entries=args.state_budget_entries,
        state_budget_bytes=args.state_budget_bytes,
        requested_top_k=args.requested_top_k,
        observation_window=args.observation_window,
        overhead_warmup=args.overhead_warmup,
        overhead_batches=args.overhead_batches,
        overhead_batch_size=args.overhead_batch_size,
        output_path=args.output or None,
    )
    print(json.dumps(report["aggregates"], indent=2))


if __name__ == "__main__":
    main()
